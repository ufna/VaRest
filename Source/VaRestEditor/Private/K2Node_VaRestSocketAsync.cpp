UK2Node_VaRestSocketAsync::UK2Node_VaRestSocketAsync() { OrphanedPinSaveMode = ESaveOrphanPinMode::SaveAll; }
const UVaRestSocketEndpoint* UK2Node_VaRestSocketAsync::ResolveEntry() const
{
	if (IsValid(Api)) for (const auto& Config : Api->Sockets)
		if (IsValid(Config.Get()) && Config->Name == Entry && Config->GetProtocolTag() == TEXT("WebSocket")) return Cast<UVaRestSocketEndpoint>(Config.Get());
	return nullptr;
}
const FVaRestSocketMessageDeclaration* UK2Node_VaRestSocketAsync::ResolveDeclaration() const
{
	const auto* Config = ResolveEntry();
	const auto Direction = Operation == EVaRestSocketCall::Request ? EVaRestSocketMessageDirection::Request
		: (Operation == EVaRestSocketCall::ListenRequest ? EVaRestSocketMessageDirection::InRequest : EVaRestSocketMessageDirection::In);
	return Config ? Config->Messages.FindByPredicate([&](const auto& Message) {
		return Message.Direction == Direction && Message.Channel.Equals(Channel, ESearchCase::CaseSensitive) && Message.Route.Equals(Route, ESearchCase::CaseSensitive);
	}) : nullptr;
}
void UK2Node_VaRestSocketAsync::AllocateDefaultPins()
{
	const bool bRequest = Operation == EVaRestSocketCall::Request;
	const auto* Declaration = ResolveDeclaration();
	const auto& InputType = bDeclaration && Declaration ? Declaration->PayloadType : PayloadType;
	const bool bTypedInput = bRequest && InputType.Kind != EVaRestTypeKind::None && (InputType.Kind != EVaRestTypeKind::Json || InputType.Container != EVaRestTypeContainer::None);
	ProxyFactoryClass = bRequest ? UVaRestSocketRequestAction::StaticClass() : UVaRestListenSocketAction::StaticClass();
	ProxyClass = ProxyFactoryClass; ProxyActivateFunctionName = GET_FUNCTION_NAME_CHECKED(UBlueprintAsyncActionBase, Activate);
	ProxyFactoryFunctionName = bRequest
		? (bTypedInput ? (bAssetEntry ? GET_FUNCTION_NAME_CHECKED(UVaRestSocketRequestAction, RequestAssetValue) : GET_FUNCTION_NAME_CHECKED(UVaRestSocketRequestAction, RequestValue))
			: (bAssetEntry ? GET_FUNCTION_NAME_CHECKED(UVaRestSocketRequestAction, RequestAsset) : GET_FUNCTION_NAME_CHECKED(UVaRestSocketRequestAction, Request)))
		: (bAssetEntry ? GET_FUNCTION_NAME_CHECKED(UVaRestListenSocketAction, ListenAsset) : GET_FUNCTION_NAME_CHECKED(UVaRestListenSocketAction, Listen));
	Super::AllocateDefaultPins();
	PinError.Reset();
	if (bTypedInput)
	{
		FEdGraphPinType InputPin;
		if (VaRest::Http::Editor::TypeToPin(InputType, InputPin, PinError)) if (auto* Pin = FindPin(TEXT("Payload"), EGPD_Input))
		{ InputPin.bIsReference = Pin->PinType.bIsReference; InputPin.bIsConst = Pin->PinType.bIsConst; Pin->PinType = InputPin; GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValueBasedOnType(Pin); }
	}
	const auto& Type = bDeclaration && Declaration ? (bRequest ? Declaration->ReplyType : Declaration->PayloadType) : (bRequest ? ReplyType : PayloadType);
	if (!FindPin(TEXT("Error"), EGPD_Output)) CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Struct, FVaRestError::StaticStruct(), TEXT("Error"));
	FCreatePinParams WarningPins; WarningPins.ContainerType = EPinContainerType::Array;
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Struct, FVaRestJsonError::StaticStruct(), TEXT("DecodeWarnings"), WarningPins);
	if (Type.Kind != EVaRestTypeKind::None && (Type.Kind != EVaRestTypeKind::Json || Type.Container != EVaRestTypeContainer::None))
	{
		FEdGraphPinType TypedPin;
		if (VaRest::Http::Editor::TypeToPin(Type, TypedPin, PinError))
		{
			if (bRequest) { if (auto* Pin = FindPin(TEXT("Reply"), EGPD_Output)) Pin->PinType = TypedPin; }
			else CreatePin(EGPD_Output, TypedPin, TEXT("Payload"));
		}
	}
	if (bAssetEntry)
	{
		if (auto* Pin = FindPin(TEXT("Api"))) { Pin->DefaultObject = Api; Pin->bHidden = true; }
		if (auto* Pin = FindPin(TEXT("Entry"))) { Pin->DefaultValue = Entry.ToString(); Pin->bHidden = true; }
	}
	if (bDeclaration)
	{
		if (auto* Pin = FindPin(TEXT("Route"))) { Pin->DefaultValue = Route; Pin->bHidden = true; }
		if (auto* Pin = FindPin(TEXT("Channel"))) { Pin->DefaultValue = Channel; Pin->bHidden = true; }
	}
	if (auto* Pin = FindPin(TEXT("bRequestsOnly"))) { Pin->DefaultValue = Operation == EVaRestSocketCall::ListenRequest ? TEXT("true") : TEXT("false"); Pin->bHidden = true; }
}
void UK2Node_VaRestSocketAsync::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	for (auto* Pin : OldPins) Pin->SetSavePinIfOrphaned(true);
	AllocateDefaultPins(); RestoreSplitPins(OldPins);
}
void UK2Node_VaRestSocketAsync::PostEditChangeProperty(FPropertyChangedEvent& Event)
{
	Super::PostEditChangeProperty(Event);
	if (Event.GetPropertyName() == GET_MEMBER_NAME_CHECKED(UK2Node_VaRestSocketAsync, Api)
		|| Event.GetPropertyName() == GET_MEMBER_NAME_CHECKED(UK2Node_VaRestSocketAsync, Entry)) bAssetEntry = true;
	ReconstructNode();
}
void UK2Node_VaRestSocketAsync::ValidateNodeDuringCompilation(FCompilerResultsLog& Log) const
{
	Super::ValidateNodeDuringCompilation(Log);
	if (!PinError.IsEmpty()) Log.Error(*FString::Printf(TEXT("@@ %s"), *PinError), this);
	const bool bRequest = Operation == EVaRestSocketCall::Request; const auto* Declaration = ResolveDeclaration();
	const auto& Type = bDeclaration && Declaration ? (bRequest ? Declaration->ReplyType : Declaration->PayloadType) : (bRequest ? ReplyType : PayloadType);
	if (Type.Kind != EVaRestTypeKind::None && (Type.Kind != EVaRestTypeKind::Json || Type.Container != EVaRestTypeContainer::None))
	{
		FEdGraphPinType Expected; FString Detail; const auto* Output = FindPin(bRequest ? TEXT("Reply") : TEXT("Payload"), EGPD_Output);
		if (!VaRest::Http::Editor::TypeToPin(Type, Expected, Detail) || !Output || Output->PinType != Expected)
			Log.Error(TEXT("@@ output no longer matches its type declaration; reconstruct and reconnect it."), this);
	}
	if (bAssetEntry)
	{
		const auto* Config = ResolveEntry();
		if (!Config) { Log.Error(TEXT("@@ has a missing API/WebSocket entry. Its pins have been retained."), this); return; }
		FVaRestApiValidationContext Validation; Config->Validate(Validation);
		for (const auto& Issue : Validation.Issues) if (!Issue.bWarning) Log.Error(*FString::Printf(TEXT("@@ %s: %s"), *Issue.PropertyPath, *Issue.Message.ToString()), this);
		if (bDeclaration && !ResolveDeclaration()) Log.Error(TEXT("@@ has a missing message declaration; restore its exact channel and route."), this);
	}
	for (const auto* Pin : Pins) if (Pin->bOrphanedPin && !Pin->LinkedTo.IsEmpty()) Log.Error(TEXT("@@ has a linked removed/incompatible pin; reconnect or remove it."), this);
}
bool UK2Node_VaRestSocketAsync::HandleDelegates(const TArray<FBaseAsyncTaskHelper::FOutputPinAndLocalVariable>& VariableOutputs,
	UEdGraphPin* ProxyObjectPin, UEdGraphPin*& InOutLastThenPin, UEdGraph* SourceGraph, FKismetCompilerContext& Compiler)
{
	// Preserve a declared unconnected wildcard's concrete default type on the engine's intermediate factory call.
	if (auto* Factory = Cast<UK2Node_CallFunction>(ProxyObjectPin->GetOwningNode()))
		if (const auto* Input = FindPin(TEXT("Payload"), EGPD_Input)) if (auto* Destination = Factory->FindPin(TEXT("Payload"), EGPD_Input))
		{
			const bool bRef = Destination->PinType.bIsReference, bConst = Destination->PinType.bIsConst;
			// An unlinked CustomStructureParam notification resets the pin to wildcard.
			if (!Destination->LinkedTo.IsEmpty()) Factory->NotifyPinConnectionListChanged(Destination);
			Destination->PinType = Input->PinType;
			Destination->PinType.bIsReference = bRef; Destination->PinType.bIsConst = bConst;
		}
	const bool bRequest = Operation == EVaRestSocketCall::Request; const auto* Declaration = ResolveDeclaration();
	const auto& Type = bDeclaration && Declaration ? (bRequest ? Declaration->ReplyType : Declaration->PayloadType) : (bRequest ? ReplyType : PayloadType);
	if (Type.Kind == EVaRestTypeKind::None || (Type.Kind == EVaRestTypeKind::Json && Type.Container == EVaRestTypeContainer::None))
		return Super::HandleDelegates(VariableOutputs, ProxyObjectPin, InOutLastThenPin, SourceGraph, Compiler);
	TMap<FName, UK2Node_TemporaryVariable*> Outputs; for (const auto& Pair : VariableOutputs) Outputs.Add(Pair.OutputPin->PinName, Pair.TempVar);
	VaRestEditor::FProtocolTransferConfig Config; Config.TypedOutput = bRequest ? TEXT("Reply") : TEXT("Payload");
	Config.SuccessExec = bRequest ? GET_MEMBER_NAME_CHECKED(UVaRestSocketRequestAction, OnReply) : GET_MEMBER_NAME_CHECKED(UVaRestListenSocketAction, OnMessage);
	Config.MetadataOutput = TEXT("Message"); Config.MetadataClass = UVaRestSocketAsyncAction::StaticClass();
	Config.MetadataGetter = GET_FUNCTION_NAME_CHECKED(UVaRestSocketAsyncAction, GetPreparedMessage);
	bool bValid = VaRestEditor::ExpandProtocolOutputBinding(this, SourceGraph, Compiler, ProxyObjectPin, InOutLastThenPin, Type, Outputs, Config);
	for (TFieldIterator<FMulticastDelegateProperty> It(ProxyClass); It && bValid; ++It)
	{
		if (It->GetFName() == Config.SuccessExec || It->GetFName() == GET_MEMBER_NAME_CHECKED(UVaRestPreparedOutputAction, OnTypedOutputUnavailable)) continue;
		UEdGraphPin* Tail = nullptr;
		bValid = FBaseAsyncTaskHelper::HandleDelegateImplementation(*It, VariableOutputs, ProxyObjectPin, InOutLastThenPin, Tail, this, SourceGraph, Compiler);
	}
	return bValid;
}
void UK2Node_VaRestSocketAsync::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* Graph)
{
	const int32 Before = Compiler.MessageLog.NumErrors; ValidateNodeDuringCompilation(Compiler.MessageLog);
	if (Before == Compiler.MessageLog.NumErrors) Super::ExpandNode(Compiler, Graph);
}
void UK2Node_VaRestSocketAsync::GetMenuActions(FBlueprintActionDatabaseRegistrar& Registrar) const
{
	if (!Registrar.IsOpenForRegistration(GetClass())) return;
	for (const auto Kind : {EVaRestSocketCall::Listen, EVaRestSocketCall::ListenRequest, EVaRestSocketCall::Request})
		Registrar.AddBlueprintAction(GetClass(), UVaRestSocketNodeSpawner::Create(nullptr, NAME_None, Kind));
}
FText UK2Node_VaRestSocketAsync::GetNodeTitle(ENodeTitleType::Type) const
{
	const TCHAR* Prefix = Operation == EVaRestSocketCall::Request ? TEXT("Socket JSON Request ")
		: (Operation == EVaRestSocketCall::ListenRequest ? TEXT("On Socket Request ") : TEXT("On Socket Message "));
	return FText::FromString(FString(Prefix) + (bDeclaration ? Route : FString()));
}
FText UK2Node_VaRestSocketAsync::GetTooltipText() const
{
	const auto* Message = ResolveDeclaration();
	return FText::FromString((Message ? Message->Description + TEXT("\n") : FString())
		+ TEXT("Delivers native messages/JSON on the game thread. Stop the Action to unregister; a shared socket stays connected."));
}
FText UK2Node_VaRestSocketAsync::GetMenuCategory() const { return NSLOCTEXT("VaRestSocketAsyncNode", "Category", "VaRest|Socket"); }
