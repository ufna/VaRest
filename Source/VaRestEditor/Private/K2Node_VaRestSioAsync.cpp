UK2Node_VaRestSioAsync::UK2Node_VaRestSioAsync() { OrphanedPinSaveMode = ESaveOrphanPinMode::SaveAll; }
const UVaRestSioEndpoint* UK2Node_VaRestSioAsync::ResolveEntry() const { return VaRestEditor::SioNodes::ResolveEntry(Api, Entry); }
const FVaRestSioEventDeclaration* UK2Node_VaRestSioAsync::ResolveDeclaration() const { return VaRestEditor::SioNodes::ResolveDeclaration(ResolveEntry(), Namespace, Event, Operation); }
void UK2Node_VaRestSioAsync::AllocateDefaultPins()
{
	PinError.Reset(); const bool bAck = Operation == EVaRestSioCall::EmitWithAck;
	ProxyFactoryClass = bAck ? UVaRestEmitSioAckAction::StaticClass() : UVaRestListenSioAction::StaticClass();
	ProxyClass = ProxyFactoryClass; ProxyActivateFunctionName = GET_FUNCTION_NAME_CHECKED(UBlueprintAsyncActionBase, Activate);
	ProxyFactoryFunctionName = bAck
		? (bAssetEntry ? GET_FUNCTION_NAME_CHECKED(UVaRestEmitSioAckAction, EmitAssetWithAck) : GET_FUNCTION_NAME_CHECKED(UVaRestEmitSioAckAction, EmitWithAck))
		: (bAssetEntry ? GET_FUNCTION_NAME_CHECKED(UVaRestListenSioAction, ListenAsset) : GET_FUNCTION_NAME_CHECKED(UVaRestListenSioAction, Listen));
	Super::AllocateDefaultPins();
	if (!FindPin(TEXT("Error"), EGPD_Output)) CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Struct, FVaRestError::StaticStruct(), TEXT("Error"));
	FCreatePinParams WarningPins; WarningPins.ContainerType = EPinContainerType::Array;
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Struct, FVaRestJsonError::StaticStruct(), TEXT("DecodeWarnings"), WarningPins);
	if (bAssetEntry)
	{
		if (auto* Pin = FindPin(TEXT("Api"))) { Pin->DefaultObject = Api; Pin->bHidden = true; }
		if (auto* Pin = FindPin(TEXT("Entry"))) { Pin->DefaultValue = Entry.ToString(); Pin->bHidden = true; }
	}
	if (auto* Pin = FindPin(TEXT("bOnce"))) { Pin->DefaultValue = bOnce ? TEXT("true") : TEXT("false"); Pin->bHidden = true; }
	const auto* Declaration = ResolveDeclaration();
	if (bDeclaration)
	{
		if (auto* Pin = FindPin(TEXT("Event"), EGPD_Input)) { Pin->DefaultValue = Event; Pin->bHidden = true; }
		if (auto* Pin = FindPin(TEXT("Namespace"))) { Pin->DefaultValue = Namespace; Pin->bHidden = true; }
		if (Declaration)
		{
			if (auto* Pin = FindPin(TEXT("ArgsMode"))) { Pin->DefaultValue = StaticEnum<EVaRestSioArgs>()->GetNameStringByValue(static_cast<int64>(Declaration->ArgsMode)); Pin->bHidden = true; }
			if (auto* Pin = FindPin(TEXT("ReplyArgsMode"))) { Pin->DefaultValue = StaticEnum<EVaRestSioArgs>()->GetNameStringByValue(static_cast<int64>(Declaration->ReplyArgsMode)); Pin->bHidden = true; }
			if (auto* Pin = FindPin(TEXT("bErrorFirst"))) { Pin->DefaultValue = Declaration->bErrorFirstReply ? TEXT("true") : TEXT("false"); Pin->bHidden = true; }
		}
	}
	const auto& OutputType = bDeclaration && Declaration ? (bAck ? Declaration->ReplyType : Declaration->PayloadType) : (bAck ? ReplyType : PayloadType);
	if (OutputType.Kind != EVaRestTypeKind::None && (OutputType.Kind != EVaRestTypeKind::Json || OutputType.Container != EVaRestTypeContainer::None))
	{
		FEdGraphPinType Type;
		if (VaRest::Http::Editor::TypeToPin(OutputType, Type, PinError))
			if (auto* Pin = FindPin(bAck ? TEXT("Reply") : TEXT("Payload"), EGPD_Output)) Pin->PinType = Type;
	}
	// Outbound reflection uses the synchronous borrowed input thunk.
	const auto& InputType = bDeclaration && Declaration ? Declaration->PayloadType : PayloadType;
	if (bAck && (bDeclaration || InputType.Kind != EVaRestTypeKind::None))
	{
		FEdGraphPinType Type;
		if (VaRestEditor::SioNodes::PayloadPinType(InputType, Type, PinError)) if (auto* Pin = FindPin(TEXT("Payload"), EGPD_Input))
		{ Type.bIsReference = Pin->PinType.bIsReference; Type.bIsConst = Pin->PinType.bIsConst; Pin->PinType = Type; GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValueBasedOnType(Pin); }
	}
}
void UK2Node_VaRestSioAsync::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	for (auto* Pin : OldPins) Pin->SetSavePinIfOrphaned(true);
	AllocateDefaultPins();
	if (bDeclaration && !ResolveDeclaration()) for (const auto* Old : OldPins) if (!Old->ParentPin && Old->PinName == TEXT("Payload") && Old->Direction == EGPD_Input)
		if (auto* Pin = FindPin(TEXT("Payload"), EGPD_Input)) Pin->PinType = Old->PinType;
	RestoreSplitPins(OldPins);
}
void UK2Node_VaRestSioAsync::NotifyPinConnectionListChanged(UEdGraphPin* Pin)
{
	Super::NotifyPinConnectionListChanged(Pin);
	if (!bDeclaration && PayloadType.Kind == EVaRestTypeKind::None && Pin && Pin->Direction == EGPD_Input && Pin->PinName == TEXT("Payload") && !Pin->LinkedTo.IsEmpty())
	{ const bool bRef = Pin->PinType.bIsReference, bConst = Pin->PinType.bIsConst; Pin->PinType = Pin->LinkedTo[0]->PinType; Pin->PinType.bIsReference = bRef; Pin->PinType.bIsConst = bConst; }
}
void UK2Node_VaRestSioAsync::PostEditChangeProperty(FPropertyChangedEvent& Change)
{
	Super::PostEditChangeProperty(Change);
	if (Change.GetPropertyName() == GET_MEMBER_NAME_CHECKED(UK2Node_VaRestSioAsync, Api) || Change.GetPropertyName() == GET_MEMBER_NAME_CHECKED(UK2Node_VaRestSioAsync, Entry)) bAssetEntry = true;
	ReconstructNode();
}
void UK2Node_VaRestSioAsync::ValidateNodeDuringCompilation(FCompilerResultsLog& Log) const
{
	Super::ValidateNodeDuringCompilation(Log);
	const auto* Declaration = ResolveDeclaration(); VaRestEditor::SioNodes::ValidateIdentity(*this, ResolveEntry(), bAssetEntry, bDeclaration, Declaration, Log);
	if (!PinError.IsEmpty()) Log.Error(*FString::Printf(TEXT("@@ %s"), *PinError), this);
	const bool bAck = Operation == EVaRestSioCall::EmitWithAck;
	const auto& Output = bDeclaration && Declaration ? (bAck ? Declaration->ReplyType : Declaration->PayloadType) : (bAck ? ReplyType : PayloadType);
	if (Output.Kind != EVaRestTypeKind::None)
	{
		FEdGraphPinType Expected; FString Error;
		if (!VaRest::Http::Editor::TypeToPin(Output, Expected, Error)) Log.Error(*FString::Printf(TEXT("@@ %s"), *Error), this);
		else if (const auto* Pin = FindPin(bAck ? TEXT("Reply") : TEXT("Payload"), EGPD_Output))
		{
			Expected.bIsReference = Pin->PinType.bIsReference; Expected.bIsConst = Pin->PinType.bIsConst;
			if (Pin->PinType != Expected) Log.Error(TEXT("@@ output no longer matches its type declaration; reconstruct and reconnect it."), this);
		}
	}
	if (bAck && bDeclaration && Declaration)
	{
		FEdGraphPinType Expected; FString Error;
		if (VaRestEditor::SioNodes::PayloadPinType(Declaration->PayloadType, Expected, Error)) if (const auto* Pin = FindPin(TEXT("Payload"), EGPD_Input))
		{ Expected.bIsReference = Pin->PinType.bIsReference; Expected.bIsConst = Pin->PinType.bIsConst; if (Expected != Pin->PinType) Log.Error(TEXT("@@ payload no longer matches its declaration; reconstruct and reconnect it."), this); }
	}
}
bool UK2Node_VaRestSioAsync::HandleDelegates(const TArray<FBaseAsyncTaskHelper::FOutputPinAndLocalVariable>& VariableOutputs,
	UEdGraphPin* ProxyObjectPin, UEdGraphPin*& InOutLastThenPin, UEdGraph* SourceGraph, FKismetCompilerContext& Compiler)
{
	if (auto* Factory = Cast<UK2Node_CallFunction>(ProxyObjectPin->GetOwningNode()))
		if (const auto* Input = FindPin(TEXT("Payload"), EGPD_Input)) if (auto* Destination = Factory->FindPin(TEXT("Payload"), EGPD_Input))
		{
			const bool bRef = Destination->PinType.bIsReference, bConst = Destination->PinType.bIsConst;
			// An unlinked CustomStructureParam notification resets the pin to wildcard.
			if (!Destination->LinkedTo.IsEmpty()) Factory->NotifyPinConnectionListChanged(Destination);
			Destination->PinType = Input->PinType;
			Destination->PinType.bIsReference = bRef; Destination->PinType.bIsConst = bConst;
		}
	const bool bAck = Operation == EVaRestSioCall::EmitWithAck; const auto* Declaration = ResolveDeclaration();
	const auto& Type = bDeclaration && Declaration ? (bAck ? Declaration->ReplyType : Declaration->PayloadType) : (bAck ? ReplyType : PayloadType);
	if (Type.Kind == EVaRestTypeKind::None || (Type.Kind == EVaRestTypeKind::Json && Type.Container == EVaRestTypeContainer::None))
		return Super::HandleDelegates(VariableOutputs, ProxyObjectPin, InOutLastThenPin, SourceGraph, Compiler);
	TMap<FName, UK2Node_TemporaryVariable*> Outputs; for (const auto& Pair : VariableOutputs) Outputs.Add(Pair.OutputPin->PinName, Pair.TempVar);
	VaRestEditor::FProtocolTransferConfig Config; Config.TypedOutput = bAck ? TEXT("Reply") : TEXT("Payload");
	Config.SuccessExec = bAck ? GET_MEMBER_NAME_CHECKED(UVaRestEmitSioAckAction, OnAck) : GET_MEMBER_NAME_CHECKED(UVaRestListenSioAction, OnEvent);
	Config.MetadataOutput = TEXT("Event"); Config.MetadataClass = UVaRestSioAsyncAction::StaticClass();
	Config.MetadataGetter = GET_FUNCTION_NAME_CHECKED(UVaRestSioAsyncAction, GetPreparedEvent); Config.bSplitMetadata = true;
	bool bValid = VaRestEditor::ExpandProtocolOutputBinding(this, SourceGraph, Compiler, ProxyObjectPin, InOutLastThenPin, Type, Outputs, Config);
	for (TFieldIterator<FMulticastDelegateProperty> It(ProxyClass); It && bValid; ++It)
	{
		if (It->GetFName() == Config.SuccessExec || It->GetFName() == GET_MEMBER_NAME_CHECKED(UVaRestPreparedOutputAction, OnTypedOutputUnavailable)) continue;
		UEdGraphPin* Tail = nullptr;
		bValid = FBaseAsyncTaskHelper::HandleDelegateImplementation(*It, VariableOutputs, ProxyObjectPin, InOutLastThenPin, Tail, this, SourceGraph, Compiler);
	}
	return bValid;
}
void UK2Node_VaRestSioAsync::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* Graph)
{ const int32 Before = Compiler.MessageLog.NumErrors; ValidateNodeDuringCompilation(Compiler.MessageLog); if (Before == Compiler.MessageLog.NumErrors) Super::ExpandNode(Compiler, Graph); }
void UK2Node_VaRestSioAsync::GetMenuActions(FBlueprintActionDatabaseRegistrar& Registrar) const
{
	if (Registrar.IsOpenForRegistration(GetClass())) for (const auto Kind : {EVaRestSioCall::Listen, EVaRestSioCall::EmitWithAck}) Registrar.AddBlueprintAction(GetClass(), UVaRestSioNodeSpawner::Create(nullptr, NAME_None, Kind));
}
FText UK2Node_VaRestSioAsync::GetNodeTitle(ENodeTitleType::Type) const
{ return FText::FromString((Operation == EVaRestSioCall::EmitWithAck ? FString(TEXT("Emit With Ack ")) : FString(TEXT("On Socket.IO Event "))) + (bDeclaration ? Event : FString())); }
FText UK2Node_VaRestSioAsync::GetTooltipText() const
{
	const auto* Declaration = ResolveDeclaration();
	return FText::FromString((Declaration ? Declaration->Description + TEXT("\n") : FString()) + TEXT("Delivers typed values and native Event/Ack metadata on the game thread. Stop the Action to unregister; shared sockets stay connected."));
}
FText UK2Node_VaRestSioAsync::GetMenuCategory() const { return NSLOCTEXT("VaRestSioAsync", "Category", "VaRest|Socket.IO"); }
