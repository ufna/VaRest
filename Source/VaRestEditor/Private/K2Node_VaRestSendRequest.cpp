bool UK2Node_VaRestRequestBase::IsAtAutogeneratedDefault(const UEdGraphPin& Pin)
{
	return Pin.DefaultValue.Len()==Pin.AutogeneratedDefaultValue.Len() &&
		FMemory::Memcmp(*Pin.DefaultValue,*Pin.AutogeneratedDefaultValue,Pin.DefaultValue.Len()*sizeof(TCHAR))==0;
}
FName UK2Node_VaRestRequestBase::ParameterPin(FName Identity)
{
	const FString Name=FString(TEXT("Param_"))+Identity.ToString(); return Name.Len()<NAME_SIZE ? FName(Name) : NAME_None;
}
FName UK2Node_VaRestRequestBase::PathPin(FStringView Name)
{
	const FTCHARToUTF8 Utf8(Name.GetData(),Name.Len());
	if (Utf8.Length()*2+5>=NAME_SIZE) return NAME_None;
	return FName(FString(TEXT("Path_"))+BytesToHex(reinterpret_cast<const uint8*>(Utf8.Get()),Utf8.Length()));
}
TArray<FString> UK2Node_VaRestRequestBase::UndeclaredPaths() const
{
	TArray<FString> Result; const auto* Endpoint=ResolveEndpoint(); if (!Endpoint) return Result;
	int32 Position=0;
	while ((Position=Endpoint->Path.Find(TEXT("{"),ESearchCase::CaseSensitive,ESearchDir::FromStart,Position))!=INDEX_NONE)
	{
		const int32 End=Endpoint->Path.Find(TEXT("}"),ESearchCase::CaseSensitive,ESearchDir::FromStart,Position+1); if (End==INDEX_NONE) break;
		const FString Name=Endpoint->Path.Mid(Position+1,End-Position-1); Position=End+1;
		const bool bDeclared=Endpoint->Params.ContainsByPredicate([&](const auto& Param) { return Param.In==EVaRestEndpointParamLocation::Path && Param.Name.Equals(Name,ESearchCase::CaseSensitive); });
		if (!bDeclared && !Name.IsEmpty() && !Result.ContainsByPredicate([&](const FString& Existing) { return Existing.Equals(Name,ESearchCase::CaseSensitive); })) Result.Add(Name);
	}
	return Result;
}
void UK2Node_VaRestRequestBase::AllocateDefaultPins()
{
	PinConstructionError.Reset(); const auto* Schema=GetDefault<UEdGraphSchema_K2>();
	const auto Input=[&](FName Name,const FEdGraphPinType& Type,bool bAdvanced=false) {
		auto* Pin=CreatePin(EGPD_Input,Type,Name); Pin->bAdvancedView=bAdvanced; Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin); return Pin;
	};
	const auto Type=[&](FName Category,UObject* Object=nullptr,EPinContainerType Container=EPinContainerType::None) {
		return FEdGraphPinType(Category,NAME_None,Object,Container,false,FEdGraphTerminalType());
	};
	CreatePin(EGPD_Input,UEdGraphSchema_K2::PC_Exec,UEdGraphSchema_K2::PN_Execute);
	for (FName Name:{UEdGraphSchema_K2::PN_Then,FName(TEXT("OnSuccess")),FName(TEXT("OnError")),FName(TEXT("OnTypedOutputUnavailable"))}) CreatePin(EGPD_Output,UEdGraphSchema_K2::PC_Exec,Name);
	if (AllowsQueue()) CreatePin(EGPD_Output,UEdGraphSchema_K2::PC_Exec,TEXT("OnQueued"));
	CreatePin(EGPD_Output,Type(UEdGraphSchema_K2::PC_Object,UVaRestRequestHandle::StaticClass()),TEXT("Handle"));
	CreatePin(EGPD_Output,Type(UEdGraphSchema_K2::PC_Struct,FVaRestResponseData::StaticStruct()),TEXT("Http"));
	CreatePin(EGPD_Output,Type(UEdGraphSchema_K2::PC_Struct,FVaRestError::StaticStruct()),TEXT("Error"));
	CreatePin(EGPD_Output,Type(UEdGraphSchema_K2::PC_Byte,StaticEnum<EVaRestTypedOutputUnavailableReason>()),TEXT("UnavailableReason"));
	if (AllowsQueue()) CreatePin(EGPD_Output,UEdGraphSchema_K2::PC_String,TEXT("QueueId"));
	FEdGraphPinType Result; FString Error;
	if (GetResponseType().Kind!=EVaRestTypeKind::None)
	{
		if (TypeToPin(GetResponseType(),Result,Error)) CreatePin(EGPD_Output,Result,TEXT("Response")); else PinConstructionError=Error;
	}
	if (GetErrorType().Kind!=EVaRestTypeKind::None)
	{
		if (TypeToPin(GetErrorType(),Result,Error)) CreatePin(EGPD_Output,Result,TEXT("ErrorBody")); else PinConstructionError=Error;
		CreatePin(EGPD_Output,UEdGraphSchema_K2::PC_Boolean,TEXT("ErrorBodyValid"));
	}
	FEdGraphPinType Query=Type(UEdGraphSchema_K2::PC_String,nullptr,EPinContainerType::Map);Query.PinValueType.TerminalCategory=UEdGraphSchema_K2::PC_String;
	Input(TEXT("Query"),Query,true); Input(TEXT("Tag"),Type(UEdGraphSchema_K2::PC_Name),true);
	if (IsEndpointNode())
	{
		if (const auto* Endpoint=ResolveEndpoint())
		{
			for (const auto& Param:Endpoint->Params)
			{
				FEdGraphPinType ParamType;
				if (!TypeToPin(Param.Type,ParamType,Error) || ParameterPin(Param.PinName).IsNone()) { PinConstructionError=TEXT("invalid or oversized endpoint parameter identity/type"); continue; }
				auto* Pin=Input(ParameterPin(Param.PinName),ParamType,!Param.bRequired); Pin->PinFriendlyName=FText::FromString(Param.Name);
				Pin->PinToolTip=Param.Description+(Param.bRemoved ? TEXT(" (removed; never sent)") : TEXT(""));
				if (!Param.Default.IsEmpty())
				{
					if (Param.Type.Container==EVaRestTypeContainer::Array)
					{
						TArray<FString> Values;FString Invalid;
						if (!ArrayParameterDefaults(Param.Type,Param.Default,Values,Invalid)) PinConstructionError=Param.Name+TEXT(": ")+Invalid;
						else Pin->PinToolTip+=TEXT("\nDefault array: ")+Param.Default;
					}
					else
					{
						const FString Invalid=Schema->IsPinDefaultValid(Pin,Param.Default,nullptr,FText::GetEmpty());
						if (Invalid.IsEmpty()) Schema->SetPinAutogeneratedDefaultValue(Pin,Param.Default); else PinConstructionError=Param.Name+TEXT(": ")+Invalid;
					}
				}
			}
			for (const auto& Name:UndeclaredPaths())
			{
				const FName Identity=PathPin(Name); if (Identity.IsNone()) { PinConstructionError=TEXT("a path parameter name exceeds the K2 pin identity limit"); continue; }
				Input(Identity,Type(UEdGraphSchema_K2::PC_String))->PinFriendlyName=FText::FromString(Name);
			}
			FEdGraphPinType Body;
			if (Endpoint->BodyKind==EVaRestEndpointBodyKind::Multipart) Body=Type(UEdGraphSchema_K2::PC_Struct,FVaRestMultipartData::StaticStruct());
			else if (Endpoint->BodyKind==EVaRestEndpointBodyKind::Text) Body=Type(UEdGraphSchema_K2::PC_String);
			else if (Endpoint->BodyKind==EVaRestEndpointBodyKind::Binary) Body=Type(UEdGraphSchema_K2::PC_Byte,nullptr,EPinContainerType::Array);
			else if (Endpoint->RequestType.Kind!=EVaRestTypeKind::None && !TypeToPin(Endpoint->RequestType,Body,Error)) PinConstructionError=Error;
			if (!Body.PinCategory.IsNone()) Input(TEXT("Body"),Body);
			if (Endpoint->BodyKind==EVaRestEndpointBodyKind::Json) Input(TEXT("BodyJson"),Type(UEdGraphSchema_K2::PC_Struct,FVaRestJson::StaticStruct()),true);
		}
	}
	else
	{
		Input(TEXT("Client"),Type(UEdGraphSchema_K2::PC_Object,UVaRestApiClient::StaticClass()));
		Input(TEXT("Verb"),Type(UEdGraphSchema_K2::PC_String))->DefaultValue=TEXT("GET");
		Input(TEXT("Path"),Type(UEdGraphSchema_K2::PC_String));
		Input(TEXT("Headers"),Type(UEdGraphSchema_K2::PC_Struct,FVaRestHeader::StaticStruct(),EPinContainerType::Array),true);
		Input(TEXT("Body"),Type(UEdGraphSchema_K2::PC_Wildcard),true);
		Input(TEXT("AuthMode"),Type(UEdGraphSchema_K2::PC_Byte,StaticEnum<EVaRestAuthMode>()),true)->DefaultValue=StaticEnum<EVaRestAuthMode>()->GetNameStringByValue(static_cast<int64>(EVaRestAuthMode::Required));
	}
}
void UK2Node_VaRestRequestBase::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	for (auto* Pin:OldPins) Pin->SetSavePinIfOrphaned(true);
	if (IsEndpointNode() && !ResolveEndpoint())
	{
		AllocateDefaultPins();
		for (const auto* Pin:OldPins) if (!Pin->ParentPin && !FindPin(Pin->PinName))
		{
			auto* Kept=CreatePin(Pin->Direction,Pin->PinType,Pin->PinName);Kept->PinFriendlyName=Pin->PinFriendlyName;
			Kept->PinToolTip=TEXT("The endpoint is unavailable. This pin and its value/links are retained until the endpoint is restored.");
			Kept->AutogeneratedDefaultValue=Pin->AutogeneratedDefaultValue;Kept->DefaultValue=Pin->DefaultValue;Kept->DefaultObject=Pin->DefaultObject;Kept->DefaultTextValue=Pin->DefaultTextValue;
		}
		RestoreSplitPins(OldPins);
	}
	else if (!IsEndpointNode())
	{
		AllocateDefaultPins();
		// Restore the concrete wildcard shape before the engine reconnects links/defaults and split members.
		for (const auto* Old:OldPins) if (!Old->ParentPin && Old->PinName==TEXT("Body"))
			if (auto* Body=FindPin(TEXT("Body"))) Body->PinType=Old->PinType;
		RestoreSplitPins(OldPins);
	}
	else Super::ReallocatePinsDuringReconstruction(OldPins);
}
UK2Node::ERedirectType UK2Node_VaRestRequestBase::DoPinsMatchForReconstruction(const UEdGraphPin* NewPin,int32 NewIndex,const UEdGraphPin* OldPin,int32 OldIndex) const
{
	if (NewPin->PinName==OldPin->PinName && NewPin->PinType!=OldPin->PinType && NewPin->PinType.PinCategory!=UEdGraphSchema_K2::PC_Wildcard) return ERedirectType_None;
	return Super::DoPinsMatchForReconstruction(NewPin,NewIndex,OldPin,OldIndex);
}
void UK2Node_VaRestRequestBase::PostReconstructNode()
{
	Super::PostReconstructNode(); SyncBodyType();
	for (auto* Pin:Pins) if (Pin->bOrphanedPin) Pin->PinToolTip=TEXT("Removed or incompatible VaRest pin. Existing links are retained; reconnect or remove this pin before compiling.");
}
void UK2Node_VaRestRequestBase::PostEditChangeProperty(FPropertyChangedEvent& Event)
{
	Super::PostEditChangeProperty(Event); if (!IsTemplate()) { ReconstructNode(); if (auto* Blueprint=FBlueprintEditorUtils::FindBlueprintForNode(this)) FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint); }
}
void UK2Node_VaRestRequestBase::SyncBodyType()
{
	if (IsEndpointNode()) return;
	if (auto* Body=FindPin(TEXT("Body")))
	{
		if (!Body->LinkedTo.IsEmpty()) Body->PinType=Body->LinkedTo[0]->PinType;
		else if (Body->SubPins.IsEmpty() && IsAtAutogeneratedDefault(*Body) && !Body->DefaultObject && Body->DefaultTextValue.IsEmpty())
			Body->PinType=FEdGraphPinType(UEdGraphSchema_K2::PC_Wildcard,NAME_None,nullptr,EPinContainerType::None,false,FEdGraphTerminalType());
	}
}
void UK2Node_VaRestRequestBase::NotifyPinConnectionListChanged(UEdGraphPin* Pin) { Super::NotifyPinConnectionListChanged(Pin); if (Pin && Pin->PinName==TEXT("Body")) SyncBodyType(); }
bool UK2Node_VaRestRequestBase::IsConnectionDisallowed(const UEdGraphPin* Mine,const UEdGraphPin* Other,FString& Reason) const
{
	if (!IsEndpointNode() && Mine && Other && Mine->PinName==TEXT("Body"))
	{
		const auto& Type=Other->PinType;
		const bool bBytes=Type.PinCategory==UEdGraphSchema_K2::PC_Byte && Type.ContainerType==EPinContainerType::Array && !Type.PinSubCategoryObject.IsValid();
		if (!bBytes && (Type.ContainerType!=EPinContainerType::None || (Type.PinCategory!=UEdGraphSchema_K2::PC_Struct && Type.PinCategory!=UEdGraphSchema_K2::PC_String)))
		{ Reason=TEXT("Request bodies accept a struct, Json, string or byte array."); return true; }
	}
	return Super::IsConnectionDisallowed(Mine,Other,Reason);
}
void UK2Node_VaRestRequestBase::ValidateNodeDuringCompilation(FCompilerResultsLog& Log) const
{
	Super::ValidateNodeDuringCompilation(Log); if (bExpanded) return;
	if (!PinConstructionError.IsEmpty()) Log.Error(*FString::Printf(TEXT("@@: %s"),*PinConstructionError),this);
	FVaRestApiValidationContext Validation;
	if (IsEndpointNode())
	{
		if (!GetApi() || !ResolveEndpoint()) { Log.Error(TEXT("@@ has a missing API/endpoint. Existing pins have been retained."),this); return; }
		GetApi()->Validate(Validation);
		if (ResolveEndpoint()->bDeprecated) Log.Warning(*FString::Printf(TEXT("@@ is deprecated: %s"),*ResolveEndpoint()->DeprecationMessage),this);
	}
	else
	{
		GetResponseType().Validate(Validation,TEXTVIEW("ResponseType")); GetErrorType().Validate(Validation,TEXTVIEW("ErrorType"));
		if (AllowsQueue() && (!FindPin(TEXT("Client")) || FindPin(TEXT("Client"))->LinkedTo.IsEmpty())) Log.Error(TEXT("@@ queueing requires an explicit client with an active named registration."),this);
	}
	for (const auto& Issue:Validation.Issues) if (!Issue.bWarning) Log.Error(*FString::Printf(TEXT("@@ %s: %s"),*Issue.PropertyPath,*Issue.Message.ToString()),this);
	for (const auto* Pin:Pins)
	{
		if (Pin->bOrphanedPin && !Pin->LinkedTo.IsEmpty()) Log.Error(TEXT("@@ has a linked removed/incompatible pin; reconnect or remove it."),this);
		if (Pin->Direction==EGPD_Input && Pin->PinType.PinCategory!=UEdGraphSchema_K2::PC_Exec && Pin->PinType.PinCategory!=UEdGraphSchema_K2::PC_Wildcard && Pin->LinkedTo.IsEmpty())
		{
			for (int32 Index=0;Index<Pin->DefaultValue.Len();++Index) if (!Pin->DefaultValue[Index]) { Log.Error(TEXT("@@ has an embedded null in a pin literal; supply that value through a runtime input."),this);break; }
			// Container inputs have no scalar pin literal. Expansion supplies asset array defaults or
			// AutoCreateRefTerm's empty Query/Headers; the generic schema cannot see that custom expansion.
			if (Pin->PinType.IsContainer())
			{
				if (!Pin->DefaultValue.IsEmpty() || Pin->DefaultObject || !Pin->DefaultTextValue.IsEmpty())
					Log.Error(TEXT("@@ container inputs require a connection or an endpoint array default, not a pin literal."),this);
				continue;
			}
			const FString Error=GetDefault<UEdGraphSchema_K2>()->IsPinDefaultValid(Pin,Pin->DefaultValue,Pin->DefaultObject,Pin->DefaultTextValue);
			if (!Error.IsEmpty()) Log.Error(*FString::Printf(TEXT("@@ %s: %s"),*Pin->PinName.ToString(),*Error),this);
		}
	}
}
void UK2Node_VaRestRequestBase::ExpandNode(FKismetCompilerContext& Compiler,UEdGraph* Graph)
{
	Super::ExpandNode(Compiler,Graph); const int32 Errors=Compiler.MessageLog.NumErrors; ValidateNodeDuringCompilation(Compiler.MessageLog);
	if (Compiler.MessageLog.NumErrors!=Errors) return;
	ExpandFullRequest(*this,Compiler,Graph); bExpanded=true;
}
