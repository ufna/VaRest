UK2Node_VaRestSocketCall::UK2Node_VaRestSocketCall() { OrphanedPinSaveMode = ESaveOrphanPinMode::SaveAll; }
const UVaRestSocketEndpoint* UK2Node_VaRestSocketCall::ResolveEntry() const
{
	if (IsValid(Api)) for (const auto& Config : Api->Sockets)
		if (IsValid(Config.Get()) && Config->Name == Entry && Config->GetProtocolTag() == TEXT("WebSocket")) return Cast<UVaRestSocketEndpoint>(Config.Get());
	return nullptr;
}
const FVaRestSocketMessageDeclaration* UK2Node_VaRestSocketCall::ResolveDeclaration() const
{
	const auto* Config = ResolveEntry();
	return Config ? Config->Messages.FindByPredicate([this](const auto& Message) {
		return Message.Direction == (Operation == EVaRestSocketCall::Reply ? EVaRestSocketMessageDirection::InRequest : EVaRestSocketMessageDirection::Out) && Message.Channel.Equals(Channel, ESearchCase::CaseSensitive)
			&& Message.Route.Equals(Route, ESearchCase::CaseSensitive);
	}) : nullptr;
}
void UK2Node_VaRestSocketCall::AllocateDefaultPins()
{
	PinError.Reset();
	if (Operation == EVaRestSocketCall::Reply) SetFromFunction(UVaRestSocketLibrary::StaticClass()->FindFunctionByName(GET_FUNCTION_NAME_CHECKED(UVaRestSocketLibrary, ReplyToSocketMessage)));
	else if (Operation == EVaRestSocketCall::Get) SetFromFunction(UVaRestSocketLibrary::StaticClass()->FindFunctionByName(GET_FUNCTION_NAME_CHECKED(UVaRestSocketLibrary, GetSocket)));
	else if (bAssetEntry) SetFromFunction(UVaRestSocketLibrary::StaticClass()->FindFunctionByName(GET_FUNCTION_NAME_CHECKED(UVaRestSocketLibrary, EmitAssetMessage)));
	else SetFromFunction(UVaRestSocketClient::StaticClass()->FindFunctionByName(GET_FUNCTION_NAME_CHECKED(UVaRestSocketClient, Emit)));
	Super::AllocateDefaultPins();
	if (bAssetEntry)
	{
		if (auto* Pin = FindPin(TEXT("Api"))) { Pin->DefaultObject = Api; Pin->bHidden = true; }
		if (auto* Pin = FindPin(TEXT("Entry"))) { Pin->DefaultValue = Entry.ToString(); Pin->bHidden = true; }
	}
	if (bDeclaration)
	{
		if (auto* Pin = FindPin(TEXT("Route"))) { Pin->DefaultValue = Route; Pin->bHidden = true; }
		if (const auto* Message = ResolveDeclaration())
		{
			FEdGraphPinType Type;
			if (VaRest::Http::Editor::TypeToPin(Operation == EVaRestSocketCall::Reply ? Message->ReplyType : Message->PayloadType, Type, PinError))
				if (auto* Pin = FindPin(TEXT("Value"))) { Type.bIsReference = Pin->PinType.bIsReference; Type.bIsConst = Pin->PinType.bIsConst; Pin->PinType = Type; GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValueBasedOnType(Pin); }
		}
	}
}
void UK2Node_VaRestSocketCall::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	for (auto* Pin : OldPins) Pin->SetSavePinIfOrphaned(true);
	AllocateDefaultPins();
	// A removed/renamed declaration retains its old payload type, values and split pins until explicitly repaired.
	if (bDeclaration && !ResolveDeclaration())
		for (const auto* Old : OldPins) if (!Old->ParentPin && Old->PinName == TEXT("Value"))
			if (auto* Pin = FindPin(TEXT("Value"))) Pin->PinType = Old->PinType;
	RestoreSplitPins(OldPins);
}
void UK2Node_VaRestSocketCall::NotifyPinConnectionListChanged(UEdGraphPin* Pin)
{
	const FEdGraphPinType Before = Pin ? Pin->PinType : FEdGraphPinType();
	Super::NotifyPinConnectionListChanged(Pin);
	if (!Pin || Pin->Direction != EGPD_Input || Pin->PinName != TEXT("Value")) return;
	if (bDeclaration)
	{
		// CallFunction resets an unlinked CustomStructureParam to wildcard. An asset declaration still owns its type.
		Pin->PinType = Before;
		if (const auto* Message = ResolveDeclaration())
		{
			FEdGraphPinType Declared; PinError.Reset();
			if (VaRest::Http::Editor::TypeToPin(Operation == EVaRestSocketCall::Reply ? Message->ReplyType : Message->PayloadType, Declared, PinError))
				Pin->PinType = Declared;
		}
	}
	else if (!Pin->LinkedTo.IsEmpty()) Pin->PinType = Pin->LinkedTo[0]->PinType;
	Pin->PinType.bIsReference = Before.bIsReference; Pin->PinType.bIsConst = Before.bIsConst;
}
void UK2Node_VaRestSocketCall::PostEditChangeProperty(FPropertyChangedEvent& Event)
{
	Super::PostEditChangeProperty(Event);
	if (Event.GetPropertyName() == GET_MEMBER_NAME_CHECKED(UK2Node_VaRestSocketCall, Api)
		|| Event.GetPropertyName() == GET_MEMBER_NAME_CHECKED(UK2Node_VaRestSocketCall, Entry)) { bAssetEntry = true; ReconstructNode(); }
}
void UK2Node_VaRestSocketCall::ValidateNodeDuringCompilation(FCompilerResultsLog& Log) const
{
	Super::ValidateNodeDuringCompilation(Log);
	if (!PinError.IsEmpty()) Log.Error(*FString::Printf(TEXT("@@: %s"), *PinError), this);
	if (bAssetEntry)
	{
		const auto* Config = ResolveEntry();
		if (!Config) { Log.Error(TEXT("@@ has a missing API/WebSocket entry. Its pins have been retained."), this); return; }
		FVaRestApiValidationContext Validation; Config->Validate(Validation);
		for (const auto& Issue : Validation.Issues) if (!Issue.bWarning) Log.Error(*FString::Printf(TEXT("@@ %s: %s"), *Issue.PropertyPath, *Issue.Message.ToString()), this);
		if (bDeclaration && !ResolveDeclaration()) Log.Error(TEXT("@@ has a missing message declaration; select or restore its exact channel and route."), this);
		if (const auto* Message = ResolveDeclaration(); bDeclaration && Message)
		{
			FEdGraphPinType Expected; FString Error;
			if (VaRest::Http::Editor::TypeToPin(Operation == EVaRestSocketCall::Reply ? Message->ReplyType : Message->PayloadType, Expected, Error))
				if (const auto* Pin = FindPin(TEXT("Value")))
				{
					Expected.bIsReference = Pin->PinType.bIsReference; Expected.bIsConst = Pin->PinType.bIsConst;
					if (Pin->PinType != Expected) Log.Error(TEXT("@@ payload pin no longer matches its declaration; reconstruct and reconnect it."), this);
				}
		}
	}
	for (const auto* Pin : Pins) if (Pin->bOrphanedPin && !Pin->LinkedTo.IsEmpty()) Log.Error(TEXT("@@ has a linked removed/incompatible pin; reconnect or remove it."), this);
}
void UK2Node_VaRestSocketCall::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* Graph)
{
	const int32 Before = Compiler.MessageLog.NumErrors; ValidateNodeDuringCompilation(Compiler.MessageLog);
	if (Before == Compiler.MessageLog.NumErrors) Super::ExpandNode(Compiler, Graph);
}
void UK2Node_VaRestSocketCall::GetMenuActions(FBlueprintActionDatabaseRegistrar& Registrar) const
{
	if (!Registrar.IsOpenForRegistration(GetClass())) return;
	for (const auto Kind : {EVaRestSocketCall::Get, EVaRestSocketCall::Emit, EVaRestSocketCall::Reply})
	{
		auto* Spawner = UVaRestSocketNodeSpawner::Create(nullptr, NAME_None, Kind);
		Registrar.AddBlueprintAction(GetClass(), Spawner);
	}
}
FText UK2Node_VaRestSocketCall::GetNodeTitle(ENodeTitleType::Type) const
{
	if (Operation == EVaRestSocketCall::Get) return FText::FromString(bAssetEntry ? TEXT("Get Socket ") + Entry.ToString() : FString(TEXT("Get Socket")));
	if (Operation == EVaRestSocketCall::Reply) return FText::FromString(bDeclaration ? TEXT("Reply ") + Route : FString(TEXT("Reply to Socket Request")));
	return FText::FromString(bDeclaration ? TEXT("Emit ") + Route : FString(TEXT("Emit Socket Message")));
}
FText UK2Node_VaRestSocketCall::GetTooltipText() const
{
	if (const auto* Message = ResolveDeclaration()) return FText::FromString(Message->Description);
	return NSLOCTEXT("VaRestSocketNode", "Description", "Uses the GameInstance socket Hub. The payload is encoded synchronously before its native bytes enter the send queue.");
}
FText UK2Node_VaRestSocketCall::GetMenuCategory() const { return NSLOCTEXT("VaRestSocketNode", "Category", "VaRest|Socket"); }
